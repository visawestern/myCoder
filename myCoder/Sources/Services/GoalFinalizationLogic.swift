import Foundation

/// Чистая логика финализации целей (директива владельца 2026-11-14).
///
/// Когда обычная цель выполнена, приложение не просто останавливается:
/// последним действием автоматически создаётся и запускается ИТОГОВАЯ
/// цель — проверка всего плана «адвокатом дьявола». Когда выполнена сама
/// итоговая цель, работа с целями останавливается полностью.
///
/// Модуль не знает о UI и хранилище: только решает, когда создавать
/// итоговую цель, и строит её (с текстом из директивы и скоупом
/// завершённой цели).
///
/// Входы: завершённая цель и контекст скоупа.
/// Выходы: решение «создавать ли финальную цель» и сама цель.
/// Зависимости: `UserGoal`, `GoalContext`.
enum GoalFinalizationLogic {

    /// Фиксированный текст итоговой цели (директива владельца 2026-11-14).
    /// Создаётся автоматически при завершении обычной цели.
    static let finalGoalTitle = """
    проверь каждый пункт плана на качество как адвокат дьявола сравнив результат проверки с ожидаемым результатом и если качество ниже 95 из 100 то предложить лучшее решение и исправлять пока качество не превысит 95 из 100 и пока весь план не будет отмечен прогрессом готовым с качеством больше 95 из 100 каждый пункт после чего план можно считать завершенным! не забывай что ты же все делаешь через TDD и все возможные тесты проверяя полученный результат с ожидаемым? так же ограничение на 600 строк кода в одном файле тоже действует а так же каждая функция должна быть модульной с комментариями о входных выходных параметрах и что она делает а так же от чего зависит + каждая функция должна быть модульной что бы ее можно было переносить куда угодно и отдельно править и проверять работу!
    """

    /// Нужно ли после завершения этой цели запустить итоговую проверку.
    ///
    /// - Parameter goal: завершённая цель.
    /// - Returns: `true` для обычной цели (создаём итоговую), `false` для
    ///   самой итоговой (цель останавливается полностью).
    static func shouldStartFinal(goal: UserGoal) -> Bool {
        !goal.isFinal
    }

    /// Создать итоговую цель по завершённой обычной.
    ///
    /// Наследует скоуп (проект/чат) завершённой цели, чтобы проверка не
    /// «уплывала» в другие чаты/проекты. Состояние — `pending`: запуск
    /// выполняется отдельно (`GoalLauncher.launch`).
    ///
    /// - Parameters:
    ///   - completed: завершённая обычная цель.
    ///   - context: контекст скоупа (fallback, если у цели его нет).
    /// - Returns: новая цель с `isFinal == true` и фиксированным текстом.
    static func finalGoal(for completed: UserGoal, context: GoalContext) -> UserGoal {
        UserGoal(
            title: finalGoalTitle,
            state: .pending,
            isFinal: true,
            projectPath: completed.projectPath ?? normalized(context.projectPath),
            chatID: completed.chatID ?? normalized(context.chatID)
        )
    }

    /// Нормализация необязательного значения: `nil`/пробелы → `nil`.
    private static func normalized(_ value: String?) -> String? {
        guard let value else { return nil }
        let trimmed = value.trimmingCharacters(in: .whitespacesAndNewlines)
        return trimmed.isEmpty ? nil : trimmed
    }
}
